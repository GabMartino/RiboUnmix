import pandas as pd
import numpy as np
import glob
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.stats import pearsonr
from tqdm import tqdm
import yaml
import os


def calculate_transcript_pcc(pred, target):
    """Safely calculate PCC for a single transcript."""
    # Need at least 2 points with non-zero variance to correlate
    if len(pred) < 2 or np.var(pred) <= 1e-12 or np.var(target) <= 1e-12:
        return np.nan
    return pearsonr(pred, target)[0]


def main():
    print("=== DATASET PERFORMANCE DIAGNOSTICS ===")

    # 1. Load Dataset Dictionary
    dict_path = "../Datasets/encodings/dataset_encoding.yaml"
    print(f"Loading dataset mapping from: {dict_path}")
    with open(dict_path, "r", encoding="utf-8") as f:
        name_to_idx = yaml.safe_load(f)

    # Invert dictionary to map ID -> Name (e.g., 3 -> 'grimson_2019')
    idx_to_name = {v: k for k, v in name_to_idx.items()}

    print("Loading distributed Parquet files...")
    # 2. Automatically load and merge all rank files generated by DDP
    parquet_files = glob.glob("riboai_queueing/comprehensive_predictions_rank*.parquet")
    if not parquet_files:
        raise FileNotFoundError("No comprehensive_predictions_rank*.parquet files found!")

    df = pd.concat([pd.read_parquet(f) for f in parquet_files], ignore_index=True)
    print(f"Successfully loaded {len(df)} total transcript-dataset interactions.")

    metrics_records = []
    depth_records = []

    print("Computing metrics and extracting read depths per dataset...")
    # Group by dataset
    for dataset_id, group in tqdm(df.groupby("dataset_id")):
        dataset_name = idx_to_name.get(dataset_id, f"Unknown_{dataset_id}")

        mu_pccs = []
        rho_pccs = []
        w_pccs = []
        read_depths = []

        for _, row in group.iterrows():
            # Extract Arrays
            mu_pred = row["mu"]
            rho_pred = row["rho"]
            w_pred = row["w_prob"]

            y_target = row["target"]
            total_scale = row["total_scale"]

            # --- NEW: Extract True Read Depth ---
            # The total reads on this transcript for this specific experiment
            read_depths.append(np.sum(y_target))

            # Reconstruct the exact biophysical targets
            safe_scale = np.maximum(total_scale, 1e-8)
            rho_target = y_target / safe_scale

            den = max(np.sum(y_target), 1e-6)
            w_target = y_target / den

            # Calculate transcript-level PCCs
            mu_pccs.append(calculate_transcript_pcc(mu_pred, y_target))
            rho_pccs.append(calculate_transcript_pcc(rho_pred, rho_target))
            w_pccs.append(calculate_transcript_pcc(w_pred, w_target))

        # Clean NaNs and take the mean
        mean_mu = np.nanmean(mu_pccs)
        mean_rho = np.nanmean(rho_pccs)
        mean_w = np.nanmean(w_pccs)
        mean_depth = np.mean(read_depths)

        # Log records for the Barplot
        metrics_records.append({"Dataset": dataset_name, "Metric": "Mu (Total Reads)", "PCC": mean_mu})
        metrics_records.append({"Dataset": dataset_name, "Metric": "Rho (Density)", "PCC": mean_rho})
        metrics_records.append({"Dataset": dataset_name, "Metric": "W_prob (Elongation)", "PCC": mean_w})

        # Log records for the Depth Scatter Plot
        depth_records.append({
            "Dataset": dataset_name,
            "Mean_Mu_PCC": mean_mu,
            "Mean_Read_Depth": mean_depth
        })

    df_metrics = pd.DataFrame(metrics_records)
    df_depth = pd.DataFrame(depth_records)

    # ==========================================
    # VISUALIZATION 1: PERFORMANCE BARPLOT
    # ==========================================
    print("Generating grouped barplot...")
    sns.set_theme(style="whitegrid", context="talk")
    plt.figure(figsize=(18, 7))

    ax1 = sns.barplot(
        data=df_metrics,
        x="Dataset",
        y="PCC",
        hue="Metric",
        palette=["#1f77b4", "#ff7f0e", "#2ca02c"],
        alpha=0.9
    )

    plt.title("Intrinsic Physics vs. Total Reads: Model Performance Across Datasets", pad=20, fontsize=18,
              fontweight='bold')
    plt.xlabel("Laboratory Dataset", labelpad=15, fontsize=14)
    plt.ylabel("Mean Pearson Correlation (PCC)", labelpad=15, fontsize=14)
    plt.xticks(rotation=45, ha='right', fontsize=10)
    plt.legend(title="Physical Target", bbox_to_anchor=(1.01, 1), loc='upper left', frameon=True)
    plt.ylim(0, 1.0)
    plt.tight_layout()

    bar_path = "dataset_performance_barplot.png"
    plt.savefig(bar_path, dpi=300, bbox_inches="tight")
    print(f"Barplot saved to: {bar_path}")

    # ==========================================
    # VISUALIZATION 2: DEPTH VS PERFORMANCE SCATTER
    # ==========================================
    print("Generating Depth vs. Performance scatter plot...")
    plt.figure(figsize=(10, 8))
    sns.set_theme(style="ticks", context="talk")

    # We correlate against the log10 of the depth, because sequencing depth follows a power law.
    # Going from 10 to 100 reads improves signal massively; 10,000 to 10,090 does almost nothing.
    log_depths = np.log10(df_depth["Mean_Read_Depth"])
    mu_pccs_array = df_depth["Mean_Mu_PCC"]

    depth_pcc, depth_pval = pearsonr(log_depths, mu_pccs_array)

    ax2 = sns.regplot(
        x=df_depth["Mean_Read_Depth"],
        y=df_depth["Mean_Mu_PCC"],
        scatter_kws={'s': 80, 'color': '#3498db', 'edgecolor': 'black', 'alpha': 0.7},
        line_kws={'color': '#e74c3c', 'linewidth': 2, 'linestyle': '--'}
    )

    # Annotate the scatter plot with dataset names for debugging
    for i, row in df_depth.iterrows():
        plt.text(row["Mean_Read_Depth"], row["Mean_Mu_PCC"] + 0.01, row["Dataset"],
                 fontsize=8, alpha=0.7, ha='center')

    # Add the correlation stat
    textstr = f'Log10 Depth vs PCC\n$r$ = {depth_pcc:.3f}\n$p$ = {depth_pval:.2e}'
    props = dict(boxstyle='round', facecolor='white', alpha=0.8, edgecolor='gray')
    ax2.text(0.05, 0.95, textstr, transform=ax2.transAxes, fontsize=12, verticalalignment='top', bbox=props)

    # Use a log scale for the X axis to compress massive libraries (like Ingolia) vs sparse ones
    plt.xscale('log')
    plt.title("Impact of Experimental Read Depth on Model Performance", pad=20, fontweight='bold')
    plt.xlabel("Mean Transcript Read Depth (Log Scale)", labelpad=15)
    plt.ylabel(r"Mean Predicted $\mu$ PCC", labelpad=15)

    sns.despine()
    plt.tight_layout()

    scatter_path = "depth_vs_performance_scatter.png"
    plt.savefig(scatter_path, dpi=300)
    print(f"Scatter plot saved to: {scatter_path}")


if __name__ == "__main__":
    main()